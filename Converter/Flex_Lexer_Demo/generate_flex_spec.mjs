/**
 * Generates one Flex scanner per language from the exact mapping tables used
 * by CSB_Multilingual. Separate specifications keep the complete 6,000+-rule
 * catalogue below Flex's finite-automaton size limit.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { sinhalaPatternMap } from '../CSB_Multilingual/src/engines/sinhala-input.js';
import { tamilPatternMap } from '../CSB_Multilingual/src/engines/tamil-mapping.js';
import { hindiPatternMap } from '../CSB_Multilingual/src/engines/hindi-mapping.js';

const folder = dirname(fileURLToPath(import.meta.url));
const outputFolder = join(folder, 'generated');
const maps = { singlish: sinhalaPatternMap, tanglish: tamilPatternMap, hinglish: hindiPatternMap };

function inferKind(source, unicode) {
  if (source.startsWith('#')) return 'native-digit';
  if (/^[aAiIuUeEoOāīūēōṛṝ]/u.test(source) && [...source].length <= 3) return 'phonetic-vowel';
  if (/\p{M}|්|்|्/u.test(unicode)) return [...unicode].length > 2 || /(?:kr|tr|shr|ksh|gy|zh|ng|nj|chh)/iu.test(source) ? 'cluster' : 'consonant-vowel-unit';
  if (/^[xXzZHqQM~'.|]+$/u.test(source)) return 'sign';
  return [...source].length > 2 ? 'consonant-vowel-unit' : 'consonant';
}

function flexQuoted(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t')}"`;
}

function cQuoted(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t')}"`;
}

function scannerPreamble(language, count) {
  return String.raw`/*
 * GENERATED FILE — do not edit directly.
 * Generated by ../generate_flex_spec.mjs from the CSB_Multilingual mapping tables.
 * Language: ${language}; complete mapping rules: ${count}.
 * Flex uses maximal munch: among all rules matching at an input position, the
 * longest match wins. Each action emits a lexical token and Unicode output.
 */
%option noyywrap nodefault 8bit
%{
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define LANGUAGE ${cQuoted(language)}
static char *unicode_output = NULL;
static size_t unicode_length = 0;

static void append_unicode(const char *text) {
  size_t length = strlen(text);
  char *next = realloc(unicode_output, unicode_length + length + 1);
  if (!next) { perror("realloc"); exit(EXIT_FAILURE); }
  unicode_output = next;
  memcpy(unicode_output + unicode_length, text, length + 1);
  unicode_length += length;
}

static void emit_token(const char *rule_id, const char *kind, const char *lexeme, const char *unicode) {
  printf("TOKEN  language=%s  kind=%s  rule=%s  lexeme=[%s]  unicode=[%s]\n", LANGUAGE, kind, rule_id, lexeme, unicode);
  append_unicode(unicode);
}

static void emit_literal(void) {
  char *literal = calloc((size_t)yyleng - 1, 1);
  if (!literal) { perror("calloc"); exit(EXIT_FAILURE); }
  memcpy(literal, yytext + 1, (size_t)yyleng - 2);
  emit_token("literal:brackets", "literal", literal, literal);
  free(literal);
}

static void emit_separator(const char *kind, const char *rule_id) {
  emit_token(rule_id, kind, yytext, yytext);
}
%}

%%
"["[^]\\n]*"]" { emit_literal(); }
[[:space:]]+ { emit_separator("whitespace", "separator:whitespace"); }
`;
}

function scannerPostamble() {
  return String.raw`
. { emit_separator("unknown", "unknown:preserved"); }
%%

int main(void) {
  yylex();
  printf("UNICODE_OUTPUT [%s]\n", unicode_output ? unicode_output : "");
  free(unicode_output);
  return EXIT_SUCCESS;
}
`;
}

function mappingRules(language, map) {
  return Object.entries(map)
    .sort(([left], [right]) => [...right].length - [...left].length || left.localeCompare(right))
    .map(([source, unicode]) => `${flexQuoted(source)} { emit_token(${cQuoted(`${language}:${source}`)}, ${cQuoted(inferKind(source, unicode))}, yytext, ${cQuoted(unicode)}); }`)
    .join('\n');
}

await mkdir(outputFolder, { recursive: true });
for (const [language, map] of Object.entries(maps)) {
  const specification = `${scannerPreamble(language, Object.keys(map).length)}${mappingRules(language, map)}\n${scannerPostamble()}`;
  await writeFile(join(outputFolder, `${language}_lexer.l`), specification, 'utf8');
  console.log(`Generated ${language}_lexer.l (${Object.keys(map).length} rules)`);
}
